    // ===== 缓动 =====
    function easeInOutCubic(p) { return p < 0.5 ? 4 * p * p * p : 1 - Math.pow(-2 * p + 2, 3) / 2; }
    function clamp01(v) { return v < 0 ? 0 : v > 1 ? 1 : v; }

    /*
     * 芽长大的曲线。刻意不对称 —— 只有 p³,没有对称的收尾。
     *
     * 因为两个圆重叠时,并集比两者的面积和小,而轮廓面积 = πR0² 是硬要求。
     * 份额转移得越早,重叠的那部分藏得越久,轮廓就瘪得越明显:
     * 用对称的 easeInOutCubic 时分裂段实测瘪掉 12.2%(半径少 6.3%,肉眼看得见);
     * 换成 p³ 只剩 5.0%(半径少 2.5%,约 0.33px,看不出来)。
     *
     * 为什么不是更高次方:p⁴ 能把瘪缩压到 3.4%,但芽会一直小到 p=0.70 才
     * 长过「画得出来」的阈值,然后在剩下的 30% 里一下子鼓到两倍大 —— 那才是真的跳。
     * p³ 时芽在 p=0.62 就越过阈值,而此刻母球半径还有 12.49px、芽心离它 11.63px,
     * 也就是**芽是在母球内部先出现、再长出来的**,不会凭空冒一个球在屏幕上。
     *
     * 收尾那点速度突变(量级 0.02px/ms)看不见,不值得为它再引入一段缓出。
     */
    function budGrowth(p) { return p * p * p; }

    // 面积份额 -> 半径。份额是「圆的面积占比」,所以半径要开方。
    function rOf(w) {
        return CFG.R0 * Math.sqrt(w);
    }

    /*
     * 角速度做成梯形:起步加速、中段匀速、收尾减速。
     * 用积分把时间映射成角度,而不是逐帧累加 —— 这样 sampleLiquid 是纯函数,
     * 任意时间都能直接求值,不用从头播放。
     */
    function spinFraction(u) {
        const R = CFG.RAMP;
        let acc;
        if (u <= R) {
            acc = (u * u) / (2 * R);
        } else if (u <= 1 - R) {
            acc = R / 2 + (u - R);
        } else {
            acc = R / 2 + (1 - 2 * R) + (R * R - Math.pow(1 - u, 2)) / (2 * R);
        }
        return acc / (1 - R);   // 归一化,使 u=1 时正好走完
    }

    /*
     * 芽脱离母球的那个角度。
     *
     * 不是拍出来的:分出来两个球要各占 1/3 面积(半径 rOf(1/3) = 7.51),
     * 母球留 2/3(半径 rOf(2/3) = 10.61),两者「刚挨上」的圆心距就是半径和
     * 18.12;而环上圆心距是弦 2·RING_D·sin(Δ/2)。反解出 Δ —— 这就是芽
     * 从母球表面掉下来的那一刻。改 R0 或 RING_D 它会自己跟着走。
     */
    const LAND_DEG = 2 * Math.asin(
        Math.min(1, (rOf(2 / 3) + rOf(1 / 3)) / (2 * CFG.RING_D))
    ) * 180 / Math.PI;

    // 三个阶段分界:C 出生、C 转够 1/3 圈、环撑齐(也是 A 起步)
    const MILESTONE = [LAND_DEG, 120, 120 + LAND_DEG, 240];
    const TOTAL_DEG = 240 + 360 * CFG.ORBIT_TURNS;

    // ===== 时间轴 =====
    // 阶段是按**角度**切的,时长反解出来 —— 这样「第二个球到 1/3 圈时第三个球
    // 分出来」就落在一个真实的阶段边界上,而不是靠凑时长凑上去。
    const SPIN_T0 = CFG.HOLD_MS;

    function spinDeg(t) {
        if (t <= SPIN_T0) return 0;
        const u = clamp01((t - SPIN_T0) / CFG.SPIN_MS);
        return TOTAL_DEG * spinFraction(u);
    }

    // 反解:角度给定,求时间。spinDeg 单调,二分就够。
    function timeAtDeg(deg) {
        let lo = SPIN_T0, hi = SPIN_T0 + CFG.SPIN_MS;
        for (let i = 0; i < 40; i++) {
            const mid = (lo + hi) / 2;
            if (spinDeg(mid) < deg) lo = mid; else hi = mid;
        }
        return (lo + hi) / 2;
    }

